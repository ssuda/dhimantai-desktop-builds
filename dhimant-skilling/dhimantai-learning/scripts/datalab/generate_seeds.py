def clinic(r: Rand):
    doctors = [(1, 'Dr. Anjana Menon', 'General medicine', 'Mon-Sat', set(range(6))),
               (2, 'Dr. Thomas Kurian', 'General medicine', 'Mon-Fri', set(range(5))),
               (3, 'Dr. Fathima Rahim', 'Paediatrics', 'Mon-Sat', set(range(6))),
               (4, 'Dr. Suresh Pillai', 'Diabetes care', 'Mon, Wed, Fri', {0, 2, 4}),
               (5, 'Dr. Lekha Varma', 'Gynaecology', 'Tue, Sat', {1, 5})]
    patients = [f'P{n:04d}' for n in range(1, 1201)]
    rows = []

    def clock(minutes):
        minutes = min(minutes, 23 * 60 + 55)
        return dt.time(minutes // 60, minutes % 60)

    for day in days(dt.date(2026, 1, 2), dt.date(2026, 3, 31)):
        if day.weekday() == 6 or day in (dt.date(2026, 1, 26), dt.date(2026, 3, 4)):
            continue
        for doctor_id, _n, _s, _d, works in doctors:
            if day.weekday() not in works:
                continue
            slots = 9 + r.below(5) if doctor_id != 5 else 14 + r.below(4)
            running_late = r.between(0, 40) + (25 if doctor_id == 2 else 0)
            for slot in range(slots):
                walk_in = r.chance(180)
                booked = None if walk_in else 9 * 60 + slot * 15
                status = 'seen'
                if not walk_in:
                    roll = r.below(1000)
                    status = 'cancelled' if roll < 60 else 'no_show' if roll < 130 + (60 if doctor_id == 5 else 0) else 'seen'
                arrived = seen = wait = None
                if status == 'seen':
                    base = 9 * 60 + slot * 15
                    arrived = base - r.below(35) + (r.below(20) if walk_in else 0)
                    arrived -= arrived % 5
                    seen = max(arrived + 5, base + running_late + r.below(20))
                    seen -= seen % 5
                    wait = seen - arrived
                rows.append([len(rows) + 1, r.pick(patients), doctor_id, day, 'walk_in' if walk_in else 'booked',
                             clock(booked) if booked is not None else None, clock(arrived) if arrived is not None else None,
                             clock(seen) if seen is not None else None, status, wait])
    tables = [
        ('doctors', 'doctor_id integer PRIMARY KEY,\n  doctor_name text NOT NULL,\n  speciality text NOT NULL,\n  clinic_days text NOT NULL',
         ['doctor_id', 'doctor_name', 'speciality', 'clinic_days'], [d[:4] for d in doctors]),
        ('appointments', 'appointment_id integer PRIMARY KEY,\n  patient_code text NOT NULL,\n'
                         '  doctor_id integer NOT NULL REFERENCES doctors,\n  visit_date date NOT NULL,\n  visit_type text NOT NULL,\n'
                         '  booked_time time,\n  arrived_time time,\n  seen_time time,\n  status text NOT NULL,\n  wait_minutes integer',
         ['appointment_id', 'patient_code', 'doctor_id', 'visit_date', 'visit_type', 'booked_time', 'arrived_time', 'seen_time',
          'status', 'wait_minutes'], [tuple(x) for x in rows]),
    ]
    return sql_file('Clinic', CLINIC_ABOUT, tables), sum(len(t[3]) for t in tables)


def generate(out: Path):
    out.mkdir(parents=True, exist_ok=True)
    about = {}
    for name, build, card in (('shop', shop, SHOP_ABOUT), ('school', school, SCHOOL_ABOUT), ('clinic', clinic, CLINIC_ABOUT)):
        text, count = build(Rand(SEED + sum(map(ord, name))))
        assert count <= 5000, f'{name}: {count} rows; keep each sample at or under 5,000 rows'
        (out / f'{name}.sql').write_text(text, encoding='utf-8', newline='\n')
        about[name] = {**card, 'rows': count}
    (out / 'about.json').write_text(json.dumps(about, indent=2, ensure_ascii=False) + '\n', encoding='utf-8', newline='\n')
    return about


