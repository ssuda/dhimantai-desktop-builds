SEED = 20260610
MASK = (1 << 64) - 1


class Rand:
    """splitmix64: tiny, fast and identical everywhere."""

    def __init__(self, seed: int):
        self.state = seed & MASK

    def next(self) -> int:
        self.state = (self.state + 0x9E3779B97F4A7C15) & MASK
        z = self.state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
        return z ^ (z >> 31)

    def below(self, n: int) -> int:
        return self.next() % n

    def between(self, low: int, high: int) -> int:
        return low + self.below(high - low + 1)

    def chance(self, per_thousand: int) -> bool:
        return self.below(1000) < per_thousand

    def pick(self, items):
        return items[self.below(len(items))]

    def sample(self, items, k):
        pool = list(items)
        out = []
        for _ in range(k):
            out.append(pool.pop(self.below(len(pool))))
        return out


def days(start: dt.date, end: dt.date):
    d = start
    while d <= end:
        yield d
        d += dt.timedelta(days=1)


def rupees(paise: int) -> str:
    return f'{paise // 100}.{paise % 100:02d}'


def literal(value) -> str:
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int):
        return str(value)
    if isinstance(value, (dt.date, dt.time)):
        return "'" + value.isoformat() + "'"
    if isinstance(value, Money):
        return value.text
    return "'" + str(value).replace("'", "''") + "'"


class Money:
    def __init__(self, paise: int):
        self.paise = paise
        self.text = rupees(paise)


def sql_file(title: str, about: dict, tables: list[tuple[str, str, list[str], list[tuple]]]) -> str:
    """CREATE TABLE with column comments, then multi-row INSERTs in a fixed order."""
    out = [f'-- {title}: synthetic sample data for the dhimantAI "Ask your data" lab.',
           '-- Generated by scripts/datalab/generate_seeds.py. Do not edit by hand.',
           '-- Every name and number is invented. No real person, shop, school or clinic.', '']
    described = {t['name']: t for t in about['tables']}
    for name, ddl, columns, rows in tables:
        out.append(f'CREATE TABLE {name} (\n  {ddl}\n);')
        out.append(f"COMMENT ON TABLE {name} IS {literal(described[name]['description'])};")
        for column, meaning in described[name]['columns'].items():
            out.append(f'COMMENT ON COLUMN {name}.{column} IS {literal(meaning)};')
        for start in range(0, len(rows), 200):
            chunk = rows[start:start + 200]
            values = ',\n'.join('(' + ', '.join(literal(v) for v in row) + ')' for row in chunk)
            out.append(f'INSERT INTO {name} ({", ".join(columns)}) VALUES\n{values};')
        out.append('')
    return '\n'.join(out)


